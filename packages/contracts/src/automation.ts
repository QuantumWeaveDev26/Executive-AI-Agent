import { Type, Static } from '@sinclair/typebox';

/**
 * Supported safe trigger types for Phase 1A offline email automation composition.
 */
export const EmailAutomationTriggerTypeSchema = Type.Union([
  Type.Literal('webhook_inbound'),
  Type.Literal('new_lead_inquiry'),
  Type.Literal('scheduled_digest'),
  Type.Literal('form_submission')
]);
export type EmailAutomationTriggerType = Static<typeof EmailAutomationTriggerTypeSchema>;

/**
 * Safe identifier pattern for template variables and condition fields.
 */
export const SafeVariableIdentifierSchema = Type.String({
  minLength: 1,
  maxLength: 64,
  pattern: '^[a-zA-Z_][a-zA-Z0-9_]*$'
});

export const FollowUpConditionOperatorSchema = Type.Union([
  Type.Literal('equals'),
  Type.Literal('not_equals'),
  Type.Literal('contains'),
  Type.Literal('exists')
]);
export type FollowUpConditionOperator = Static<typeof FollowUpConditionOperatorSchema>;

export const EmailFollowUpConditionSchema = Type.Object(
  {
    field: SafeVariableIdentifierSchema,
    operator: FollowUpConditionOperatorSchema,
    value: Type.Optional(Type.String({ minLength: 1, maxLength: 256 })),
    delayMinutes: Type.Integer({ minimum: 0, maximum: 43200 })
  },
  { additionalProperties: false }
);
export type EmailFollowUpCondition = Static<typeof EmailFollowUpConditionSchema>;

/**
 * Input schema for `automation.email.compose_workflow`.
 */
export const ComposeEmailWorkflowInputSchema = Type.Object(
  {
    workflowName: Type.String({ minLength: 3, maxLength: 120 }),
    triggerType: EmailAutomationTriggerTypeSchema,
    emailSubject: Type.String({ minLength: 1, maxLength: 200 }),
    emailBodyTemplate: Type.String({ minLength: 1, maxLength: 10000 }),
    allowedVariables: Type.Array(SafeVariableIdentifierSchema, {
      minItems: 1,
      maxItems: 50
    }),
    followUpConditions: Type.Optional(
      Type.Array(EmailFollowUpConditionSchema, { maxItems: 20 })
    ),
    recipientVariable: Type.Optional(SafeVariableIdentifierSchema)
  },
  { additionalProperties: false }
);
export type ComposeEmailWorkflowInput = Static<typeof ComposeEmailWorkflowInputSchema>;

/**
 * Strictly typed offline n8n workflow blueprint schema (declarative nodes only, active=false).
 * Validated against this offline schema, but NOT verified against a live n8n server in Phase 1A.
 */
export const SafeN8nNodeTypeSchema = Type.Union([
  Type.Literal('n8n-nodes-base.webhook'),
  Type.Literal('n8n-nodes-base.scheduleTrigger'),
  Type.Literal('n8n-nodes-base.if'),
  Type.Literal('n8n-nodes-base.wait'),
  Type.Literal('n8n-nodes-base.set')
]);
export type SafeN8nNodeType = Static<typeof SafeN8nNodeTypeSchema>;

export const N8nWorkflowNodeSchema = Type.Object(
  {
    id: Type.String({ minLength: 1 }),
    name: Type.String({ minLength: 1 }),
    type: SafeN8nNodeTypeSchema,
    typeVersion: Type.Number({ minimum: 1 }),
    position: Type.Tuple([Type.Number(), Type.Number()]),
    parameters: Type.Record(Type.String(), Type.Unknown())
  },
  { additionalProperties: false }
);
export type N8nWorkflowNode = Static<typeof N8nWorkflowNodeSchema>;

export const N8nConnectionTargetSchema = Type.Object(
  {
    node: Type.String({ minLength: 1 }),
    type: Type.Literal('main'),
    index: Type.Integer({ minimum: 0 })
  },
  { additionalProperties: false }
);

export const N8nWorkflowBlueprintSchema = Type.Object(
  {
    name: Type.String({ minLength: 3, maxLength: 120 }),
    active: Type.Literal(false),
    versionId: Type.String({ minLength: 1 }),
    nodes: Type.Array(N8nWorkflowNodeSchema, { minItems: 2 }),
    connections: Type.Record(
      Type.String(),
      Type.Object(
        {
          main: Type.Array(Type.Array(N8nConnectionTargetSchema))
        },
        { additionalProperties: false }
      )
    ),
    settings: Type.Object(
      {
        executionOrder: Type.Literal('v1'),
        saveManualExecutions: Type.Boolean()
      },
      { additionalProperties: false }
    ),
    meta: Type.Object(
      {
        generatedBy: Type.Literal('thaara-v2-offline-workflow-builder'),
        importReadiness: Type.Literal('offline_schema_validated_not_live_verified'),
        externallyVerifiedWithLiveN8n: Type.Literal(false)
      },
      { additionalProperties: false }
    )
  },
  { additionalProperties: false }
);
export type N8nWorkflowBlueprint = Static<typeof N8nWorkflowBlueprintSchema>;

/**
 * Canonical Thaara V2 Email Automation Workflow Definition generated by `automation.email.compose_workflow`.
 */
export const EmailAutomationWorkflowDefinitionSchema = Type.Object(
  {
    schemaVersion: Type.Literal('thaara.email_automation.v1'),
    workflowId: Type.String({ minLength: 1 }),
    workflowName: Type.String({ minLength: 3, maxLength: 120 }),
    triggerType: EmailAutomationTriggerTypeSchema,
    recipientVariable: SafeVariableIdentifierSchema,
    emailSubject: Type.String({ minLength: 1, maxLength: 200 }),
    emailBodyTemplate: Type.String({ minLength: 1, maxLength: 10000 }),
    allowedVariables: Type.Array(SafeVariableIdentifierSchema, { minItems: 1 }),
    referencedVariables: Type.Array(SafeVariableIdentifierSchema),
    followUpConditions: Type.Array(EmailFollowUpConditionSchema),
    n8nBlueprint: N8nWorkflowBlueprintSchema
  },
  { additionalProperties: false }
);
export type EmailAutomationWorkflowDefinition = Static<typeof EmailAutomationWorkflowDefinitionSchema>;

/**
 * Input schema for `automation.email.dry_run_test`.
 * Performs a safe, offline sandbox dry run using sample customer data without sending any real email.
 */
export const DryRunSampleValueSchema = Type.Union([
  Type.String({ maxLength: 2000 }),
  Type.Number(),
  Type.Boolean()
]);

export const DryRunEmailWorkflowInputSchema = Type.Object(
  {
    workflowName: Type.String({ minLength: 3, maxLength: 120 }),
    triggerType: EmailAutomationTriggerTypeSchema,
    emailSubject: Type.String({ minLength: 1, maxLength: 200 }),
    emailBodyTemplate: Type.String({ minLength: 1, maxLength: 10000 }),
    allowedVariables: Type.Array(SafeVariableIdentifierSchema, {
      minItems: 1,
      maxItems: 50
    }),
    followUpConditions: Type.Optional(
      Type.Array(EmailFollowUpConditionSchema, { maxItems: 20 })
    ),
    recipientVariable: Type.Optional(SafeVariableIdentifierSchema),
    sampleData: Type.Record(Type.String(), DryRunSampleValueSchema)
  },
  { additionalProperties: false }
);
export type DryRunEmailWorkflowInput = Static<typeof DryRunEmailWorkflowInputSchema>;

export const DryRunConditionEvaluationSchema = Type.Object(
  {
    field: SafeVariableIdentifierSchema,
    operator: FollowUpConditionOperatorSchema,
    expectedValue: Type.Union([Type.String(), Type.Null()]),
    actualValue: Type.Union([Type.String(), Type.Null()]),
    matched: Type.Boolean(),
    delayMinutes: Type.Integer({ minimum: 0 })
  },
  { additionalProperties: false }
);
export type DryRunConditionEvaluation = Static<typeof DryRunConditionEvaluationSchema>;

export const EmailWorkflowDryRunReportSchema = Type.Object(
  {
    dryRunPassed: Type.Boolean(),
    workflowName: Type.String(),
    triggerType: EmailAutomationTriggerTypeSchema,
    referencedVariables: Type.Array(Type.String()),
    missingVariables: Type.Array(Type.String()),
    undeclaredVariables: Type.Array(Type.String()),
    securityViolations: Type.Array(Type.String()),
    conditionsSatisfied: Type.Boolean(),
    conditionEvaluations: Type.Array(DryRunConditionEvaluationSchema),
    renderedPreview: Type.Union([
      Type.Object(
        {
          recipient: Type.String(),
          subject: Type.String(),
          body: Type.String(),
          totalDelayMinutes: Type.Integer({ minimum: 0 })
        },
        { additionalProperties: false }
      ),
      Type.Null()
    ]),
    realEmailSent: Type.Literal(false),
    externalDeploymentStatus: Type.Literal('not_configured'),
    externalAccountsContacted: Type.Literal(false)
  },
  { additionalProperties: false }
);
export type EmailWorkflowDryRunReport = Static<typeof EmailWorkflowDryRunReportSchema>;

