export function isRealCustomerName(name: string | undefined | null): boolean {
  if (!name) return false;
  const trimmed = name.trim();
  if (trimmed.length < 2 || trimmed.length > 50) return false;
  if (/[\r\n\t]/.test(trimmed)) return false;
  // Strictly reject email addresses, @ symbols, URLs, domain names
  if (/@/.test(trimmed)) return false;
  if (/\b(?:https?:\/\/|www\.)/i.test(trimmed)) return false;
  if (/\b[a-z0-9-]+\.(?:com|in|org|net|io|ai|co|app|xyz|dev|biz)\b/i.test(trimmed)) return false;
  // Reject key-value labels / separators
  if (/\b(?:name|email|mail|business|company|service|phone|whatsapp)\s*[:\-]/i.test(trimmed)) return false;
  // Reject placeholder names and test strings
  if (/^(?:customer|business|user|client|owner|admin|unknown|someone|none|na|n\/a|test|demo)$/i.test(trimmed)) return false;
  if (/\b(?:owner\s+test|test\s+phone|owner\s+phone|test\s+contact|test\s+number|pilot\s+phone|synthetic|test\s+user)\b/i.test(trimmed)) return false;
  if (/^(?:c_\d+|wa_\d+|\+?\d+|contact_\d+|r_\d+)$/i.test(trimmed)) return false;
  if (/^\+?\d[\d\s-]{6,}$/.test(trimmed)) return false;
  if (/[0-9_]{3,}/.test(trimmed)) return false;
  // Reject business categories and action phrases mistakenly captured as name
  if (/\b(?:clothing|apparel|garments?|textiles?|fashion|boutique|tailoring|clinic|hospital|doctor|retail|store|shop|real\s+estate|restaurant|hotel|consultation|appointment|meeting|automation|marketing)\b/i.test(trimmed)) return false;
  if (/^(?:book\s+me|book\s+a|arrange\s+a|schedule\s+a|need\s+a|want\s+a)\b/i.test(trimmed)) return false;
  return true;
}

