/**
 * Deterministically extracts structured customer enquiry and lead status from saved WhatsApp messages.
 * Distinguishes stored contact opt-in, explicit message consent evidence, revoked opt-out, and unknown consent provenance (WA-04).
 */
export function extractWhatsAppCustomerEnquiry(input: ExtractEnquiryInput): WhatsAppCustomerEnquiry | null {
  const inbound = [...input.messages]
    .filter(m => m.direction === 'inbound' && m.textPreview.trim().length > 0)
    .sort((a, b) => a.timestamp.localeCompare(b.timestamp));

  if (inbound.length === 0) return null;

  const memory = buildConversationMemoryState(input);
  const sessionInbound = memory.previousMessages.filter(m => m.direction === 'inbound');
  const activeInbound = sessionInbound.length > 0 ? sessionInbound : inbound;
  const latestInbound = activeInbound[activeInbound.length - 1]!;
  const activeInboundTexts = activeInbound.map(m => m.textPreview);
  const combinedInbound = activeInboundTexts.join('\n');
  const detectedLanguage = detectCustomerMessageLanguage(latestInbound.textPreview);

  let optOutRequested = false;
  let explicitConsentTimestamp: string | null = null;
  for (const m of inbound) {
    const hasOptOut = OPT_OUT_PATTERN.test(m.textPreview);
    if (hasOptOut) {
      optOutRequested = true;
      explicitConsentTimestamp = null;
      continue;
    }
    if (
      EXPLICIT_CONSENT_PATTERN.test(m.textPreview) ||
      CALLBACK_PATTERN.test(m.textPreview) ||
      APPOINTMENT_PATTERN.test(m.textPreview) ||
      Boolean(extractPreferredCallbackTime([m.textPreview]))
    ) {
      explicitConsentTimestamp = m.timestamp;
    }
  }

  const humanHandoffRequested = HUMAN_HANDOFF_PATTERN.test(latestInbound.textPreview);
  const injectionDetected = PROMPT_INJECTION_PATTERN.test(combinedInbound);
  const sensitiveRequest = SENSITIVE_REQUEST_PATTERN.test(combinedInbound);
  const preferredCallbackTime = memory.preferredAppointmentTime;
  const hasContextualAppointmentSlot =
    Boolean(preferredCallbackTime) &&
    (memory.appointmentStatus === 'REQUESTED' || memory.appointmentStatus === 'CONFIRMED');
  const callbackRequested = CALLBACK_PATTERN.test(combinedInbound) || hasContextualAppointmentSlot;
  const appointmentInterest =
    APPOINTMENT_PATTERN.test(combinedInbound) ||
    hasContextualAppointmentSlot ||
    memory.appointmentStatus === 'DISCUSSING' ||
    memory.appointmentStatus === 'REQUESTED' ||
    memory.appointmentStatus === 'AWAITING_CUSTOMER_BOOKING' ||
    memory.appointmentStatus === 'CONFIRMED';
  const needsPricingOrScopeReview = PRICING_OR_GUARANTEE_PATTERN.test(combinedInbound);

  const requestedService = memory.interestedService;
  const businessCategory = memory.businessCategory;
  const customerName = memory.customerName;
  const businessName = memory.businessName;
  const businessProblem = memory.customerRequirements;

  const isAutomatedNonText = isAutomatedOrNonTextCustomerMessage(latestInbound.textPreview);
  const domainRecognized =
    Boolean(requestedService || businessCategory || businessName || businessProblem || callbackRequested || appointmentInterest || needsPricingOrScopeReview) ||
    KNOWN_DOMAIN_OR_GREETING_PATTERN.test(combinedInbound);
  const uncertainQuery = !isAutomatedNonText && !optOutRequested && !humanHandoffRequested && !injectionDetected && !sensitiveRequest && !domainRecognized;
  const sensitiveOrUncertain = sensitiveRequest || uncertainQuery;

  let escalationReason: WhatsAppEscalationReason | undefined;
  if (optOutRequested) escalationReason = 'opt_out';
  else if (injectionDetected) escalationReason = 'prompt_injection';
  else if (humanHandoffRequested) escalationReason = 'human_handoff';
  else if (sensitiveRequest) escalationReason = 'sensitive_request';
  else if (uncertainQuery) escalationReason = 'uncertain_query';

  const recoveryAttentionNeeded =
    input.autoReplyStatus === 'expired_reservation' || input.autoReplyStatus === 'recovery_attention_required';

  let leadStatus: WhatsAppLeadStatus = 'Enquired';
  if ((input.appointmentRecord?.status === 'CONFIRMED' || input.verifiedAppointment === true) && !optOutRequested && !injectionDetected && !sensitiveOrUncertain && !recoveryAttentionNeeded) {
    leadStatus = 'Booked appointment';
  } else if (optOutRequested || humanHandoffRequested || injectionDetected || sensitiveOrUncertain || recoveryAttentionNeeded) {
    leadStatus = 'Needs review';
  } else if (callbackRequested || appointmentInterest || input.appointmentRecord?.status === 'REQUESTED') {
    leadStatus = 'Callback requested';
  } else if (needsPricingOrScopeReview) {
    leadStatus = 'Needs review';
  }

  const summaryParts: string[] = [];
  if (input.autoReplyStatus === 'expired_reservation') {
    summaryParts.push('Auto-reply reservation expired unsent (owner attention required)');
  } else if (input.autoReplyStatus === 'recovery_attention_required') {
    summaryParts.push('Auto-reply recovery failed (owner attention required)');
  }
  if (optOutRequested) summaryParts.push('Customer requested opt-out');
  if (injectionDetected) summaryParts.push('Untrusted instruction/injection blocked');
  if (humanHandoffRequested) summaryParts.push('Requested human team handoff');
  if (sensitiveRequest) summaryParts.push('Sensitive request escalated for human review');
  if (uncertainQuery) summaryParts.push('Unverified/out-of-scope query escalated for human review');
  if (requestedService) summaryParts.push(`Service: ${requestedService}`);
  if (businessProblem) summaryParts.push(`Requirements: ${businessProblem}`);
  if (businessCategory) summaryParts.push(`Category: ${businessCategory}`);
  if (businessName) summaryParts.push(`Business: ${businessName}`);
  const hasAppointmentFlow =
    appointmentInterest ||
    callbackRequested ||
    memory.appointmentStatus === 'REQUESTED' ||
    memory.appointmentStatus === 'AWAITING_CUSTOMER_BOOKING' ||
    memory.appointmentStatus === 'CONFIRMED' ||
    leadStatus === 'Booked appointment' ||
    leadStatus === 'Callback requested';

  if (hasAppointmentFlow) {
    if (leadStatus === 'Booked appointment' || memory.appointmentStatus === 'CONFIRMED') {
      summaryParts.push('Consultation: CONFIRMED');
    } else {
      summaryParts.push('Consultation: Link shared directly (Calendly)');
    }
  }
  if (!summaryParts.length) {
    summaryParts.push(cleanSnippet(latestInbound.textPreview, 160) || 'Customer inbound enquiry');
  }

  const enquirySummary = cleanSnippet(summaryParts.join(' · '), 240);

  // WA-04: Distinguish stored contact opt-in, explicit message consent evidence, revoked opt-out, and unknown provenance.
  // Inbound customer conversations from unregistered numbers are eligible for in-window service replies,
  // but do NOT inherit blanket marketing/promotional opt-in consent without explicit message consent.
  const isAutoRegisteredCustomer = /^c_\d{7,15}$/.test(input.recipientId);
  const contactOptedIn = input.optedIn === true && !isAutoRegisteredCustomer;
  let consentProvenance: WhatsAppConsentProvenance;
  let consentRecorded = false;
  let consentTimestamp: string | null = null;
  if (optOutRequested) {
    consentProvenance = 'revoked_opt_out';
  } else if (explicitConsentTimestamp !== null) {
    consentProvenance = 'explicit_message_consent';
    consentRecorded = true;
    consentTimestamp = explicitConsentTimestamp;
  } else if (contactOptedIn) {
    consentProvenance = 'stored_contact_opt_in';
  } else {
    consentProvenance = 'unknown';
  }

  const autoReplyStatus: WhatsAppAutoReplyStatus | undefined =
    input.autoReplyStatus ?? (escalationReason ? 'escalated' : undefined);

  const latestCustomerMessage = cleanSnippet(latestInbound.textPreview, 240);
  const businessType = memory.businessType ?? extractBusinessType(activeInboundTexts, memory.lastQuestionAsked);

  const baseEnquiry: WhatsAppCustomerEnquiry = {
    recipientId: input.recipientId,
    customerName,
    maskedPhone: input.maskedPhone,
    ...(businessName ? { businessName } : {}),
    ...(businessCategory ? { businessCategory } : {}),
    ...(businessType ? { businessType } : {}),
    ...(memory.customerEmail ? { customerEmail: memory.customerEmail } : {}),
    ...(memory.emailDeclined ? { emailDeclined: true } : {}),
    ...(requestedService ? { requestedService } : {}),
    ...(businessProblem ? { businessProblem } : {}),
    ...(memory.referredWebsite ? { referredWebsite: memory.referredWebsite } : {}),
    ...(latestCustomerMessage ? { latestCustomerMessage } : {}),
    enquirySummary,
    callbackRequested: callbackRequested || appointmentInterest,
    appointmentInterest,
    ...(preferredCallbackTime ? { preferredCallbackTime } : {}),
    contactOptedIn,
    consentProvenance,
    consentRecorded,
    consentTimestamp,
    detectedLanguage,
    ...(optOutRequested ? { optOutRequested: true as const } : {}),
    ...(humanHandoffRequested ? { humanHandoffRequested: true as const } : {}),
    ...(injectionDetected ? { injectionDetected: true as const } : {}),
    ...(sensitiveOrUncertain ? { sensitiveOrUncertain: true as const } : {}),
    ...(escalationReason ? { escalationReason } : {}),
    ...(autoReplyStatus ? { autoReplyStatus } : {}),
    ...(input.appointmentRecord?.status
      ? { appointmentStatus: input.appointmentRecord.status }
      : (memory.appointmentStatus === 'REQUESTED' || memory.appointmentStatus === 'CONFIRMED' || memory.appointmentStatus === 'LINK_SENT' || memory.appointmentStatus === 'AWAITING_CUSTOMER_BOOKING' || memory.appointmentStatus === 'DISCUSSING'
        ? { appointmentStatus: memory.appointmentStatus }
        : {})),
    ...(input.appointmentRecord?.calendlyUrl ? { calendlyUrl: input.appointmentRecord.calendlyUrl } : {}),
    ...(input.appointmentRecord?.calendlyBookingId ? { calendlyBookingId: input.appointmentRecord.calendlyBookingId } : {}),
    ...(input.appointmentRecord?.calendarEventId ? { calendarEventId: input.appointmentRecord.calendarEventId } : {}),
    ...(input.appointmentRecord?.confirmedAt ? { calendarConfirmedAt: input.appointmentRecord.confirmedAt } : {}),
    leadStatus,
    conversationRef: {
      connectionId: input.connectionId,
      recipientId: input.recipientId,
      lastInboundMessageId: latestInbound.providerMessageId ?? null,
      lastMessageAt: latestInbound.timestamp
    }
  };

  if (!optOutRequested) {
    const draftProposal = buildQuantumWeaveCustomerReply({
      enquiry: baseEnquiry,
      latestCustomerMessage: latestInbound.textPreview,
      optedIn: true,
      windowOpen: true,
      hasPriorReply: memory.introducedCompany,
      memory
    });
    if (draftProposal.allowed && draftProposal.replyText) {
      baseEnquiry.suggestedReply = draftProposal.replyText.slice(0, 1024);
    }
  }

  return baseEnquiry;
}

