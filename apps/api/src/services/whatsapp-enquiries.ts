/**
 * Deduplicates identical or duplicate paragraphs in WhatsApp responses.
 */
export function deduplicateParagraphs(text: string): string {
  if (!text || typeof text !== 'string') return text;
  const rawSections = text.split(/\n{2,}/).map(s => s.trim()).filter(Boolean);
  const seen = new Set<string>();
  const uniqueSections: string[] = [];
  for (const sec of rawSections) {
    const key = sec.toLowerCase().replace(/\s+/g, ' ');
    if (!seen.has(key)) {
      seen.add(key);
      uniqueSections.push(sec);
    }
  }
  return uniqueSections.join('\n\n');
}

/**
 * Formats WhatsApp text into readable short paragraphs of approximately 2 lines each,
 * separated by blank lines (\n\n).
 * - Leaves short responses (1-2 sentences, <= 160 chars) unchanged.
 * - Protects URLs before splitting so links remain completely intact and clickable.
 * - Supports English (.!?), Hindi (।॥!?), and Kannada (.!?) sentence terminators.
 * - Completely deterministic (zero extra model/API calls).
 * - Always keeps everything in ONE WhatsApp message.
 */
export function formatWhatsAppParagraphs(text: string): string {
  if (!text || typeof text !== 'string') return text;
  const trimmed = text.trim();
  if (trimmed.length === 0) return trimmed;

  const urls: string[] = [];
  const urlRegex = /https?:\/\/[^\s)\]>"']+/gi;
  const tokenized = trimmed.replace(urlRegex, match => {
    let cleanUrl = match;
    let trailingPunct = '';
    while (/[.,!?;:]$/.test(cleanUrl)) {
      trailingPunct = cleanUrl.slice(-1) + trailingPunct;
      cleanUrl = cleanUrl.slice(0, -1);
    }
    const idx = urls.length;
    urls.push(cleanUrl);
    return `__WA_URL_${idx}__${trailingPunct}`;
  });

  const rawSections = tokenized.split(/\n{2,}/);
  const formattedSections: string[] = [];

  for (const section of rawSections) {
    const secTrimmed = section.trim();
    if (secTrimmed.length === 0) continue;

    const lines = secTrimmed.split(/\n/);
    if (lines.length > 1) {
      formattedSections.push(secTrimmed);
      continue;
    }

    const sentenceSplitRegex = /([.!?।॥]+[\s"'\)\]]+)(?=[A-Z\u0900-\u097F\u0C80-\u0CFF])/g;
    const parts: string[] = [];
    let lastIndex = 0;
    let m: RegExpExecArray | null;

    while ((m = sentenceSplitRegex.exec(secTrimmed)) !== null) {
      const matchEnd = m.index + m[0].length;
      parts.push(secTrimmed.slice(lastIndex, matchEnd).trim());
      lastIndex = matchEnd;
    }
    if (lastIndex < secTrimmed.length) {
      parts.push(secTrimmed.slice(lastIndex).trim());
    }

    const sentences = parts.filter(s => s.length > 0);
    if (secTrimmed.length <= 160 || sentences.length <= 1) {
      formattedSections.push(secTrimmed);
      continue;
    }

    const paragraphs: string[] = [];
    for (let i = 0; i < sentences.length; i += 2) {
      const chunk = sentences.slice(i, i + 2).join(' ');
      paragraphs.push(chunk);
    }
    formattedSections.push(paragraphs.join('\n\n'));
  }

  let result = formattedSections.join('\n\n');
  for (let i = 0; i < urls.length; i++) {
    result = result.replace(new RegExp(`__WA_URL_${i}__`, 'g'), () => urls[i] ?? '');
  }

  return result.trim();
}

export const EMAIL_PATTERN = /\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b/i;

export const EMAIL_DECLINE_PATTERN =
  /\b(?:no\s+(?:email|mail)|don'?t\s+(?:have|want\s+to\s+give|share|provide)\s+(?:an?\s+)?(?:email|mail)?|skip(?:\s+email)?|not\s+now|prefer\s+whatsapp(?:\s+only)?|no\s+thanks?|won'?t\s+share|without\s+email)\b|ಇಲ್ಲ|ಬೇಡ|ನಂತರ|ईमेल\s+नहीं|नहीं\s+है|नहीं\s+देना/i;

export function extractCustomerEmail(
  texts: string[],
  lastQuestionAsked?: WhatsAppConversationQuestionTopic
): { email?: string; declined?: boolean; invalidAttempt?: boolean } {
  let email: string | undefined;
  let declined = false;
  let invalidAttempt = false;

  for (const text of texts) {
    if (EMAIL_DECLINE_PATTERN.test(text)) {
      declined = true;
    }
    const match = text.match(EMAIL_PATTERN);
    if (match?.[0]) {
      const candidate = match[0].toLowerCase().trim();
      if (candidate.length <= 120) {
        email = candidate;
        declined = false;
      }
    } else if (/@/.test(text) && !match) {
      invalidAttempt = true;
    }
  }

  if (!email && !declined && lastQuestionAsked === 'customer_email' && texts.length > 0) {
    const latest = texts[texts.length - 1]?.trim() ?? '';
    if (latest.length > 0 && !EMAIL_DECLINE_PATTERN.test(latest) && !EMAIL_PATTERN.test(latest)) {
      invalidAttempt = true;
    }
  }

  return { email, declined, invalidAttempt };
}

export function formatAppointmentNaturalSlot(slotText?: string, startAtIso?: string, timeZone = 'Asia/Kolkata'): string {
  if (startAtIso) {
    try {
      const date = new Date(startAtIso);
      if (!Number.isNaN(date.getTime())) {
        const now = new Date();
        const dateDayStr = date.toLocaleDateString('en-CA', { timeZone });
        const nowDayStr = now.toLocaleDateString('en-CA', { timeZone });
        const tomorrow = new Date(now.getTime() + 24 * 3600 * 1000);
        const tomorrowDayStr = tomorrow.toLocaleDateString('en-CA', { timeZone });

        const timeParts = date.toLocaleTimeString('en-US', {
          timeZone,
          hour: 'numeric',
          minute: '2-digit',
          hour12: true
        });
        const cleanTime = timeParts.replace(':00 ', ' ');

        if (dateDayStr === nowDayStr) {
          return `today at ${cleanTime}`;
        }
        if (dateDayStr === tomorrowDayStr) {
          return `tomorrow at ${cleanTime}`;
        }
        const weekday = date.toLocaleDateString('en-US', { timeZone, weekday: 'long' });
        const dayMonth = date.toLocaleDateString('en-US', { timeZone, day: 'numeric', month: 'short' });
        return `on ${weekday}, ${dayMonth} at ${cleanTime}`;
      }
    } catch {
      // fallback
    }
  }

  if (slotText) {
    let clean = slotText
      .replace(/\s*\([^)]*Asia\/Kolkata[^)]*\)/gi, '')
      .replace(/\s*(?:on\s+)?Google\s+Calendar\.?/gi, '')
      .trim();
    if (/^\d{1,2}(?::\d{2})?\s*(?:am|pm)$/i.test(clean)) {
      return `today at ${clean.toUpperCase()}`;
    }
    if (/^(?:today|tomorrow|monday|tuesday|wednesday|thursday|friday|saturday|sunday)\b/i.test(clean)) {
      if (!/\bat\b/i.test(clean) && /\d{1,2}(?::\d{2})?\s*(?:am|pm)/i.test(clean)) {
        clean = clean.replace(/(\d{1,2}(?::\d{2})?\s*(?:am|pm))/i, 'at $1');
      }
      return clean;
    }
    return clean;
  }

  return 'today at 5 PM';
}

