export function stripForbiddenPricingFromReply(text: string): string {
  // Strip any pricing numbers, currencies, and amounts to prevent invented or historical pricing disclosures
  let masked = text.replace(/(?:₹|Rs\.?|INR|\$)\s*\d[\d,.]*(?:\s*(?:\/-|only|per\s+\w+|k|lakh|cr|\/mo(?:nth)?))?/gi, '');
  masked = masked.replace(/\b(?:999|9,999|14,999|9,750|15,870|24,950|13,650|20,750|32,850)\b/g, '');
  return masked.replace(/[^\S\r\n]{2,}/g, ' ').trim();
}

