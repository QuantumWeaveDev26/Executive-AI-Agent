  /\b(?:what\s+can\s+(?:we|i)\s+expect(?:\s+from\s+(?:you|thaara|quantum\s+weave))?|what\s+to\s+expect(?:\s+from\s+(?:you|thaara|quantum\s+weave))?|what\s+should\s+(?:we|i)\s+expect|what\s+do\s+(?:we|i)\s+expect|what\s+will\s+(?:we|i)\s+get)\b|ಏನು\s+ನಿರೀಕ್ಷಿಸಬಹುದು|क्या\s+उम्मीद\s+(?:कर\s+सकते|है)/i;

const USE_CASE_REQUIREMENT_PATTERN =
  /\b((?:both\s+)?(?:customer\s+support|lead\s+generation|lead\s+qualification|appointment\s+booking|order\s+(?:updates|tracking)|follow[\s-]*ups?|patient\s+enquir(?:y|ies)|faq\s+automation)(?:\s+(?:and|&|,)\s+(?:customer\s+support|lead\s+generation|lead\s+qualification|appointment\s+booking|order\s+(?:updates|tracking)|follow[\s-]*ups?|patient\s+enquir(?:y|ies)|faq\s+automation))+)/i;

function extractBusinessProblem(texts: string[], selectedServiceTurnIndex = -1): string | undefined {
  for (const text of texts) {
    const useCaseMatch = USE_CASE_REQUIREMENT_PATTERN.exec(text);
    if (useCaseMatch?.[1]) {
      return cleanSnippet(useCaseMatch[1], 180);
    }
  }
  for (const text of texts) {
    const match =
      /\b(?:we\s+(?:need\s+help\s+with|are\s+struggling\s+with|are\s+facing|want\s+to\s+solve|want\s+to\s+automate|want\s+to\s+build|need\s+to\s+improve)|i\s+(?:want\s+to\s+automate|want|need|require|look\s+for)|problem\s+is|challenge\s+is|issue\s+is|looking\s+for\s+help\s+with)\s+([^.!?\n]{4,180})/i.exec(
        text
      );
    if (match?.[1]) {
      const candidate = cleanSnippet(match[1], 180);
      const isJustService = /^(?:whatsapp(?:\s+automation)?|digital\s+marketing|business\s+automation|ai\s+agents?|executive\s+ai|visual\s+storytelling)$/i.test(
        candidate.trim()
      );
      if (!isJustService) {
        return candidate;
      }
    }
  }
  if (selectedServiceTurnIndex >= 0) {
    for (let i = selectedServiceTurnIndex + 1; i < texts.length; i++) {
      const turn = texts[i]!.trim();
      if (!turn || isAutomatedOrNonTextCustomerMessage(turn) || isClosingAcknowledgementOnly(turn)) continue;
      if (
        OPT_OUT_PATTERN.test(turn) ||
        HUMAN_HANDOFF_PATTERN.test(turn) ||
        PROMPT_INJECTION_PATTERN.test(turn) ||
        SENSITIVE_REQUEST_PATTERN.test(turn) ||
        PRICING_OR_GUARANTEE_PATTERN.test(turn) ||
        CALLBACK_PATTERN.test(turn) ||
        APPOINTMENT_PATTERN.test(turn) ||
        ASKS_HOW_IT_WORKS_PATTERN.test(turn) ||
        Boolean(matchNumberedService(turn)) ||
        Boolean(extractPreferredCallbackTime([turn]))
      ) {
        continue;
      }
      const cleaned = cleanSnippet(turn.replace(/[.!?]+$/, ''), 180);
      if (cleaned.length >= 4) return cleaned;
    }
  }
  return undefined;
}

export function isAutomatedOrNonTextCustomerMessage(text: string): boolean {
  const trimmed = text.trim();
  if (!trimmed) return true;
  if (!/[A-Za-z0-9\u0900-\u097F\u0C80-\u0CFF]/.test(trimmed)) return true;
  return AUTOMATED_RESPONDER_PATTERN.test(trimmed);
}

export function isClosingAcknowledgementOnly(text: string): boolean {
  return CLOSING_ACKNOWLEDGEMENT_ONLY_PATTERN.test(text.trim());
}

