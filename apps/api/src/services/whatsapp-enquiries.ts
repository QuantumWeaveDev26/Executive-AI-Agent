export function matchNumberedService(text: string): QuantumWeaveServiceItem | undefined {
  const trimmed = text.trim();
  const numMatch =
    /^(?:(?:service|option|number|#)\s*)?([1-6])(?:st|nd|rd|th)?(?:\.|\b)/i.exec(trimmed) ??
    /\b(?:service|option|number|#)\s*([1-6])(?:st|nd|rd|th)?\b/i.exec(trimmed);
  if (numMatch?.[1]) {
    const n = parseInt(numMatch[1], 10);
    return QUANTUM_WEAVE_STANDARD_SERVICES.find(s => s.number === n);
  }
  return undefined;
}

